// Master palette: every colour the four v34 level 1 towers use, read out of
// the frozen versions/sprout-siege-v34.html so the answer never drifts.
//
//   node tools/sprite/palette.js
//
// Writes, next to this file:
//   master-palette.json   colours, the tower canvas, the season grounds
//   master-palette.png    swatch image for the reference pack
//   ref/<family>-L1.png   the four reference towers, one art pixel per pixel

const fs = require('fs');
const path = require('path');
const L = require('./lib');

const SRC = path.join(L.ROOT, 'versions', 'sprout-siege-v34.html');
const FAMS = ['gnome', 'sprink', 'zap', 'hive'];
// brief decision 17 and the framework's "grounds to read on"
const GROUNDS = { spring: '#93dcaa', summer: '#7fcf8c', autumn: '#a9b878', winter: '#e3ecf0' };

const src = fs.readFileSync(SRC, 'utf8');
const re = /ART\.(gnome|sprink|zap|hive)=mkSpriteP\((\[[^\]]*\]),(\{[^}]*\})\); ART\.\1\._s=2;/g;
const towers = {}; let m;
while ((m = re.exec(src))) towers[m[1]] = { rows: JSON.parse(m[2]), pal: JSON.parse(m[3]) };
for (const f of FAMS) if (!towers[f]) throw new Error('could not find the ' + f + ' tower in ' + SRC);

const count = new Map(), fam = {}, bottoms = {};
let W = 0, H = 0;
fs.mkdirSync(path.join(L.DIR, 'ref'), { recursive: true });
for (const f of FAMS) {
  const { rows, pal } = towers[f]; W = rows[0].length; H = rows.length;
  const img = L.blank(W, H), used = new Set();
  rows.forEach((row, y) => [...row].forEach((ch, x) => { const c = pal[ch]; if (c) { L.put(img, x, y, L.rgb(c)); used.add(c.toLowerCase()); } }));
  L.savePNG(path.join(L.DIR, 'ref', f + '-L1.png'), img);
  const b = L.bbox(img); bottoms[f] = b.b; fam[f] = { colours: used.size, drawn: b.w + 'x' + b.h, bottom: b.b };
  used.forEach(c => count.set(c, (count.get(c) || 0) + 1));
}

// order for people: greys first, then by hue, dark to light inside each hue
const info = [...count.keys()].map(h => { const lab = L.lab(L.rgb(h)), ch = Math.hypot(lab[1], lab[2]); return { h, L: lab[0], ch, hue: (Math.atan2(lab[2], lab[1]) * 180 / Math.PI + 360) % 360 }; });
const band = c => c.ch < 0.035 ? -1 : Math.floor(((c.hue + 15) % 360) / 30);
info.sort((a, b) => band(a) - band(b) || a.L - b.L);
const colours = info.map(c => c.h);

// the row most towers stand on: the lowest drawn row of the reference art
const tally = {}; Object.values(bottoms).forEach(b => tally[b] = (tally[b] || 0) + 1);
const bottom = +Object.keys(tally).sort((a, b) => tally[b] - tally[a])[0];

const out = {
  note: 'Generated by tools/sprite/palette.js from versions/sprout-siege-v34.html. Do not edit by hand.',
  canvas: { w: W, h: H, bottom },
  ink: '#1d1828',
  grounds: GROUNDS,
  families: fam,
  colours,
};
fs.writeFileSync(L.PALETTE_FILE, JSON.stringify(out, null, 1) + '\n');

// swatch: 10 across, hex under each, grouped the same way as the list
const COLS = 10, CELL = 96, GAP = 14, LAB = 22, PAD = 28, HEAD = 60;
const rowsN = Math.ceil(colours.length / COLS);
const sw = L.blank(PAD * 2 + COLS * CELL + (COLS - 1) * GAP, HEAD + PAD + rowsN * (CELL + LAB + GAP), [36, 32, 44, 255]);
L.text(sw, PAD, 22, 'SPROUT SIEGE MASTER PALETTE: ' + colours.length + ' COLOURS FROM THE V34 LEVEL 1 TOWERS', [255, 238, 221], 3);
colours.forEach((h, i) => {
  const x = PAD + (i % COLS) * (CELL + GAP), y = HEAD + Math.floor(i / COLS) * (CELL + LAB + GAP);
  L.fill(sw, x, y, CELL, CELL, L.rgb(h));
  L.text(sw, x + Math.round((CELL - L.textW(h, 2)) / 2), y + CELL + 6, h, [203, 180, 149], 2);
});
L.savePNG(path.join(L.DIR, 'master-palette.png'), sw);

let near = 0;
for (let i = 0; i < info.length; i++) for (let j = i + 1; j < info.length; j++) if (L.dist(L.rgb(info[i].h), L.rgb(info[j].h)) < 0.02) near++;
console.log('master palette: ' + colours.length + ' colours (' + [...count.values()].filter(v => v > 1).length + ' shared by two or more towers)');
FAMS.forEach(f => console.log('  ' + f.padEnd(7) + fam[f].colours + ' colours, drawn ' + fam[f].drawn + ', lowest row ' + fam[f].bottom));
console.log('tower canvas ' + W + 'x' + H + ', feet on row ' + bottom);
console.log('pairs too close to tell apart (could merge): ' + near);
console.log('wrote master-palette.json, master-palette.png, ref/*.png');
